const messages: Record<Language, Record<MessageKey, string>> = {
  en,
  "zh-CN": zhCN,
};

export function translate(
  language: Language,
  key: MessageKey,
  params: MessageParams = {},
) {
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}
